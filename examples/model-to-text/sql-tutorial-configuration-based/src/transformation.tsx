/** @jsx createExprNode */

/**
 * Model-to-text tutorial, Part 3: the layout of the generated text
 * becomes a decision.
 *
 * Parts 1 and 2 each committed to one file structure, and both were
 * right for some project and wrong for another. Nothing in a relational
 * schema says whether its DDL should ship as one script, as tables plus
 * constraints, or as one file per table: that is a property of the
 * project the script is deployed into, not of the model. A question the
 * source model cannot answer is exactly what a variation point is for.
 *
 * So the whole document structure is a @VarPoint whose options each
 * return a complete <M2T> expression, and the run's configuration model
 * picks one. Identifier quoting is a second, much smaller variation
 * point over the same mechanism, showing that the two do not have to be
 * the same size to be the same kind of thing.
 *
 * Both issues are global (see decision-model.tsx): they are answered
 * once per run rather than once per table, so the binding model has no
 * per-element bindings at all.
 */
import { createExprNode } from '@aelastics/synthesis/jsx'
import type { ExprNode } from '@aelastics/synthesis/jsx'
import { M2M } from '@aelastics/synthesis/m2m'
import { M2T, Doc, Sec, P } from '@aelastics/synthesis/m2t'
import type { ModelStore } from '@aelastics/synthesis/store'
import * as m2tmm from '@aelastics/synthesis/m2t'
import { DecisionAwareM2M, VarPoint, VarOption, Default, Option } from '@aelastics/synthesis/variability'
import * as cm from '@aelastics/synthesis/metamodels/configuration/model'
import * as rmT from '@synthesis/standard-metamodels/rel-tutorial/model'

/** One foreign key: the column that points, and the column it points at. */
type ForeignKey = {
  table: rmT.ITable
  column: rmT.IColumn
  targetTable: rmT.ITable
  targetColumn: rmT.IColumn
}

@M2M()
export class RelToSqlConfigurableTransformation extends DecisionAwareM2M<
  rmT.IRelSchema,
  m2tmm.M2T_Model,
  {},
  cm.IConfigurationModel
> {
  // A configuration-based transformation takes the run's configuration
  // model as a third argument. It is optional: without one, every
  // variation point falls back to its @Default option.
  constructor(store: ModelStore, extra?: {}, configModel?: cm.IConfigurationModel) {
    super(store, extra ?? {}, configModel)
  }

  // The template does nothing but hand over to the variation point. The
  // decision is the first thing the transformation makes, because
  // everything else depends on it.
  template(s: rmT.IRelSchema): ExprNode<rmT.IRelSchema, m2tmm.M2T_Model> {
    return this.documentLayout(s)
  }

  // ######### START OutputLayout variations #############

  // The variation point. Its body never runs: the dispatcher looks up
  // the option selected for the OutputLayout issue in the run's
  // configuration model and calls that method instead.
  @VarPoint('OutputLayout')
  documentLayout(s: rmT.IRelSchema): ExprNode<rmT.IRelSchema, m2tmm.M2T_Model> {
    throw new Error('Not implemented VarOptions for VarPoint OutputLayout')
  }

  // Part 1's shape: everything in one file, references inline. The
  // simplest thing to read, and correct as long as the tables can be
  // ordered so that no reference points forward.
  @VarOption('documentLayout', Option('SingleFile'))
  singleFileLayout(s: rmT.IRelSchema): ExprNode<rmT.IRelSchema, m2tmm.M2T_Model> {
    return (
      <M2T name={`${s.name}_sql`}>
        <Doc name={`${s.name}.sql`}>
          {this.headerSection('header', `-- SQL DDL generated by Synthesis from ${s.name}`)}
          {this.tablesOf(s).map((tab) => this.tableToCreate(s, tab, true))}
        </Doc>
      </M2T>
    )
  }

  // Part 2's shape, and the default. Foreign keys can be circular, so
  // creating every table before constraining any of them is the only
  // structure that always applies cleanly.
  //
  // @Default matches isDefault on TablesAndConstraints in the decision
  // model: with no configuration model at all, the dispatcher falls back
  // to this option instead of throwing.
  @Default()
  @VarOption('documentLayout', Option('TablesAndConstraints'))
  tablesAndConstraintsLayout(s: rmT.IRelSchema): ExprNode<rmT.IRelSchema, m2tmm.M2T_Model> {
    return (
      <M2T name={`${s.name}_sql`}>
        <Doc name={`${s.name}.sql`}>
          {this.headerSection('header', `-- Tables of ${s.name}, generated by Synthesis`)}
          {this.tablesOf(s).map((tab) => this.tableToCreate(s, tab, false))}
        </Doc>
        {this.constraintsDocument(s)}
      </M2T>
    )
  }

  // One file per table, plus the shared constraints file. The layout a
  // schema-per-directory repository wants, where each table is reviewed
  // and versioned on its own.
  @VarOption('documentLayout', Option('FilePerTable'))
  filePerTableLayout(s: rmT.IRelSchema): ExprNode<rmT.IRelSchema, m2tmm.M2T_Model> {
    return (
      <M2T name={`${s.name}_sql`}>
        {this.tablesOf(s).map((tab) => (
          <Doc name={`${tab.name}.sql`}>
            {this.headerSection(
              `header_${tab.name}`,
              `-- Table ${tab.name} of ${s.name}, generated by Synthesis`
            )}
            {this.tableToCreate(s, tab, false)}
          </Doc>
        ))}
        {this.constraintsDocument(s)}
      </M2T>
    )
  }

  // ######### END OutputLayout variations #############

  // The pieces every layout is built from. They are ordinary rules: the
  // decision is about which documents exist and what goes in them, not
  // about how a CREATE TABLE statement looks.

  headerSection(name: string, comment: string): ExprNode<m2tmm.ISection> {
    return (
      <Sec name={name}>
        <P>{comment}</P>
        <P>{' '}</P>
      </Sec>
    )
  }

  tableToCreate(s: rmT.IRelSchema, tab: rmT.ITable, inlineReferences: boolean): ExprNode<m2tmm.ISection> {
    const cols = tab.columns ?? []
    return (
      <Sec name={`table_${tab.name}`}>
        <P>{`CREATE TABLE ${this.quoteIdentifier(tab.name)} (`}</P>
        {cols.map((c, i) => (
          <P>{`  ${this.columnLine(s, c, inlineReferences)}${i < cols.length - 1 ? ',' : ''}`}</P>
        ))}
        <P>{');'}</P>
        <P>{' '}</P>
      </Sec>
    )
  }

  // The constraints file only exists in the layouts that took the
  // references out of the CREATE TABLE statements.
  constraintsDocument(s: rmT.IRelSchema): ExprNode<m2tmm.IDocument> {
    return (
      <Doc name={`${s.name}-constraints.sql`}>
        {this.headerSection(
          'constraints-header',
          `-- Foreign key constraints of ${s.name}, generated by Synthesis`
        )}
        {this.foreignKeysOf(s).map((fk) => this.foreignKeyToAlter(fk))}
      </Doc>
    )
  }

  foreignKeyToAlter(fk: ForeignKey): ExprNode<m2tmm.ISection> {
    const constraint = this.quoteIdentifier(`fk_${fk.table.name}_${fk.column.name}`)
    return (
      <Sec name={`constraint_${fk.table.name}_${fk.column.name}`}>
        <P>{`ALTER TABLE ${this.quoteIdentifier(fk.table.name)} ADD CONSTRAINT ${constraint}`}</P>
        <P>
          {`  FOREIGN KEY (${this.quoteIdentifier(fk.column.name)}) REFERENCES ` +
            `${this.quoteIdentifier(fk.targetTable.name)}(${this.quoteIdentifier(fk.targetColumn.name)});`}
        </P>
        <P>{' '}</P>
      </Sec>
    )
  }

  private columnLine(s: rmT.IRelSchema, c: rmT.IColumn, inlineReferences: boolean): string {
    const parts: string[] = [this.quoteIdentifier(c.name), c.type]
    if (c.isKey) {
      parts.push('PRIMARY KEY')
    }
    if (c.isAutoincrement) {
      parts.push('AUTOINCREMENT')
    }
    if (!c.isNullable) {
      parts.push('NOT NULL')
    }
    if (inlineReferences && c.references) {
      const target = c.references
      parts.push(
        `REFERENCES ${this.quoteIdentifier(this.tableOwning(s, target).name)}(${this.quoteIdentifier(target.name)})`
      )
    }
    return parts.join(' ')
  }

  // ######### START IdentifierQuoting variations #############

  @VarPoint('IdentifierQuoting')
  quoteIdentifier(name: string): string {
    throw new Error('Not implemented VarOptions for VarPoint IdentifierQuoting')
  }

  @Default()
  @VarOption('quoteIdentifier', Option('Unquoted'))
  unquotedIdentifier(name: string): string {
    return name
  }

  @VarOption('quoteIdentifier', Option('DoubleQuoted'))
  doubleQuotedIdentifier(name: string): string {
    return `"${name}"`
  }

  // ######### END IdentifierQuoting variations #############

  private tablesOf(s: rmT.IRelSchema): rmT.ITable[] {
    return s.elements.filter((el) => this.context.store.isTypeOf(el, rmT.Table)) as rmT.ITable[]
  }

  // Every referencing column of the schema, paired with the table and
  // column it points at.
  private foreignKeysOf(s: rmT.IRelSchema): ForeignKey[] {
    const keys: ForeignKey[] = []
    for (const table of this.tablesOf(s)) {
      for (const column of table.columns ?? []) {
        if (column.references) {
          keys.push({
            table,
            column,
            targetTable: this.tableOwning(s, column.references),
            targetColumn: column.references
          })
        }
      }
    }
    return keys
  }

  // A column does not know its table, so the table a REFERENCES clause
  // has to name is the one whose columns contain the referenced column.
  private tableOwning(s: rmT.IRelSchema, col: rmT.IColumn): rmT.ITable {
    const owner = this.tablesOf(s).find((tab) => (tab.columns ?? []).some((c) => c.name === col.name))
    if (!owner) {
      throw new Error(`Column '${col.name}' is referenced but belongs to no table of schema '${s.name}'`)
    }
    return owner
  }
}
