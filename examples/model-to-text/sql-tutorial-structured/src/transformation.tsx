/** @jsx createExprNode */

/**
 * Model-to-text tutorial, Part 2: the same DDL, reorganized. Two things
 * change relative to Part 1, and both are about structure rather than
 * content.
 *
 * First, the output is two documents instead of one, and every <Doc> in
 * an M2T model becomes one file. The split is not cosmetic: foreign keys
 * can be circular (two tables referencing each other, or a table
 * referencing itself), so no ordering of CREATE TABLE statements can
 * satisfy every inline REFERENCES clause. Production DDL therefore
 * creates all tables first and adds the foreign keys afterwards with
 * ALTER TABLE. The document structure follows the deployment order.
 *
 * Second, content is placed rather than emitted in order. The documents
 * declare empty named sections (`tables`, `constraints`), and the rules
 * that produce statements sit at the top level of the <M2T> model and
 * point at the section they belong to with <SecParent $refByName=...>.
 * A rule no longer has to be written where its output ends up, which is
 * what lets one rule feed either document.
 */
import { createExprNode } from '@synthesis/jsx-runtime'
import type { ExprNode } from '@synthesis/jsx-runtime'
import { abstractM2M, M2T, Doc, Sec, SecParent, P } from '@synthesis/engine'
import type { ModelStore } from '@synthesis/engine'
import * as m2tmm from '@synthesis/engine'
import * as rmT from '@synthesis/standard-metamodels/rel-tutorial/model'

/** One foreign key: the column that points, and the column it points at. */
type ForeignKey = {
  table: rmT.ITable
  column: rmT.IColumn
  targetTable: rmT.ITable
  targetColumn: rmT.IColumn
}

export class RelToSqlStructuredTransformation extends abstractM2M<rmT.IRelSchema, m2tmm.M2T_Model> {
  constructor(store: ModelStore) {
    super(store)
  }

  template(s: rmT.IRelSchema) {
    return (
      <M2T name={`${s.name}_sql`}>
        {/* The two files, declared as empty scaffolding. Everything
            below fills them in by name. */}
        <Doc name={`${s.name}.sql`}>
          <Sec name="tables-header">
            <P>{`-- Tables of ${s.name}, generated by Synthesis`}</P>
            <P>{' '}</P>
          </Sec>
          <Sec name="tables"></Sec>
        </Doc>
        <Doc name={`${s.name}-constraints.sql`}>
          <Sec name="constraints-header">
            <P>{`-- Foreign key constraints of ${s.name}, generated by Synthesis`}</P>
            <P>{`-- Apply after ${s.name}.sql: references may be circular, so`}</P>
            <P>{'-- every table has to exist before any of them is constrained.'}</P>
            <P>{' '}</P>
          </Sec>
          <Sec name="constraints"></Sec>
        </Doc>

        {this.tablesOf(s).map((tab) => this.tableToCreate(tab))}
        {this.foreignKeysOf(s).map((fk) => this.foreignKeyToAlter(fk))}
      </M2T>
    )
  }

  // Produced at the top level of the model, placed into the `tables`
  // section of the first document. The column lines carry no REFERENCES
  // clause any more: the reference has moved to the other file.
  tableToCreate(tab: rmT.ITable): ExprNode<m2tmm.ISection> {
    const cols = tab.columns ?? []
    return (
      <Sec name={`table_${tab.name}`}>
        <SecParent $refByName="tables"></SecParent>
        <P>{`CREATE TABLE ${tab.name} (`}</P>
        {cols.map((c, i) => (
          <P>{`  ${this.columnLine(c)}${i < cols.length - 1 ? ',' : ''}`}</P>
        ))}
        <P>{');'}</P>
        <P>{' '}</P>
      </Sec>
    )
  }

  // The same top-level shape, placed into the second document instead.
  // Nothing but the section name decides which file this ends up in.
  foreignKeyToAlter(fk: ForeignKey): ExprNode<m2tmm.ISection> {
    const constraint = `fk_${fk.table.name}_${fk.column.name}`
    return (
      <Sec name={`constraint_${fk.table.name}_${fk.column.name}`}>
        <SecParent $refByName="constraints"></SecParent>
        <P>{`ALTER TABLE ${fk.table.name} ADD CONSTRAINT ${constraint}`}</P>
        <P>{`  FOREIGN KEY (${fk.column.name}) REFERENCES ${fk.targetTable.name}(${fk.targetColumn.name});`}</P>
        <P>{' '}</P>
      </Sec>
    )
  }

  private columnLine(c: rmT.IColumn): string {
    const parts: string[] = [c.name, c.type]
    if (c.isKey) {
      parts.push('PRIMARY KEY')
    }
    if (c.isAutoincrement) {
      parts.push('AUTOINCREMENT')
    }
    if (!c.isNullable) {
      parts.push('NOT NULL')
    }
    return parts.join(' ')
  }

  private tablesOf(s: rmT.IRelSchema): rmT.ITable[] {
    return s.elements.filter((el) => this.context.store.isTypeOf(el, rmT.Table)) as rmT.ITable[]
  }

  // Every referencing column of the schema, paired with the table and
  // column it points at. A column is a foreign key exactly when it has a
  // reference, so this walk is the complete list.
  private foreignKeysOf(s: rmT.IRelSchema): ForeignKey[] {
    const tables = this.tablesOf(s)
    const keys: ForeignKey[] = []
    for (const table of tables) {
      for (const column of table.columns ?? []) {
        if (column.references) {
          keys.push({
            table,
            column,
            targetTable: this.tableOwning(s, column.references),
            targetColumn: column.references
          })
        }
      }
    }
    return keys
  }

  // A column does not know its table, so the table an ALTER TABLE
  // statement has to name is the one whose columns contain the
  // referenced column.
  private tableOwning(s: rmT.IRelSchema, col: rmT.IColumn): rmT.ITable {
    const owner = this.tablesOf(s).find((tab) => (tab.columns ?? []).some((c) => c.name === col.name))
    if (!owner) {
      throw new Error(`Column '${col.name}' is referenced but belongs to no table of schema '${s.name}'`)
    }
    return owner
  }
}
