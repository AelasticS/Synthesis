/** @jsx createExprNode */

import { createExprNode } from "@aelastics/synthesis/jsx"
import { ExprNode } from "@aelastics/synthesis/jsx"
import { M2T, Doc, P, Sec, SecParent } from "@aelastics/synthesis/m2t"
import { ModelStore } from "@aelastics/synthesis/store"
import { E2E, M2M } from "@aelastics/synthesis/m2m"
import * as m2tmm from "@aelastics/synthesis/m2t"
import * as rmT from "relational-metamodel/model"
import { VarPoint, VarOption, Option, Default, DecisionAwareM2M } from "@aelastics/synthesis/variability"
import * as cm from "@aelastics/synthesis/metamodels/configuration/model"

/**
 * Model-to-text transformation that turns a rich relational schema into
 * SQL DDL: CREATE TABLE statements with composite-aware PRIMARY KEY
 * clauses (read from the PrimaryKey element, in its order), named
 * foreign key constraints as ALTER TABLE statements in a separate
 * section (foreign keys can be circular, so no creation order can
 * satisfy them inline), CREATE INDEX statements, domain rendering per
 * the DomainHandling issue, referential rules per ReferentialActions
 * (native clauses or trigger emulation; connect rules are always
 * triggers, no dialect has a declarative form), row-history capture
 * stubs for every table carrying historyOf (equally unconditional),
 * and physical clustering per the per-table Clustering issue flavored
 * by SqlDialect. Identifiers are emitted per IdentifierQuoting.
 */
@M2M()
export class Rel2DdlTransformation extends DecisionAwareM2M<
  rmT.IRelSchema,
  m2tmm.M2T_Model,
  {},
  cm.IConfigurationModel
> {
  constructor(store: ModelStore, extra?: {}, configModel?: cm.IConfigurationModel) {
    super(store, extra ?? {}, configModel)
  }

  topRule(s: rmT.IRelSchema) {
    const store = this.context.store
    const tables = (s.elements ?? []).filter((el) => store.isTypeOf(el, rmT.Table)) as rmT.ITable[]
    const domains = (s.elements ?? []).filter((el) => store.isTypeOf(el, rmT.Domain)) as rmT.IDomain[]
    const fks = tables.flatMap((tab) => ((tab.foreignKeys ?? []) as rmT.IForeignKey[]))
    const clustered = tables.filter((tab) => this.clusteringOf(tab) === "pk")
    const connectFks = fks.filter((fk) => fk.onConnect !== undefined && fk.onConnect !== null)
    const emulatedFks = this.disconnectTriggerFks(fks)
    const triggerFks = [...connectFks, ...emulatedFks.filter((fk) => !connectFks.includes(fk))]
    const historyTables = tables.filter((tab) => tab.historyOf !== undefined && tab.historyOf !== null)
    return (
      <M2T name={`${s.name}_ddl`}>
        <Doc name={`${s.name}.sql`}>
          <Sec name="header">
            <P>{`-- SQL DDL generated by Synthesis from ${s.name}`}</P>
            <P>{" "}</P>
          </Sec>
          <Sec name="domains"></Sec>
          <Sec name="tables"></Sec>
          <Sec name="constraints"></Sec>
          <Sec name="indexes"></Sec>
          <Sec name="physical"></Sec>
        </Doc>
        {this.domainsHandling(domains)}
        {tables.map((tab) => this.tableToCreate(tab))}
        {fks.map((fk) => this.foreignKeyToAlter(fk))}
        {tables.flatMap((tab) => ((tab.indexes ?? []) as rmT.IIndex[]).map((ix) => this.indexToCreate(ix)))}
        {clustered.length > 0 && this.dialect() === "postgres" ? this.postgresClusterSection(clustered) : []}
        {triggerFks.length > 0 || historyTables.length > 0 ? this.triggersDocument(s, connectFks, emulatedFks, historyTables) : []}
      </M2T>
    )
  }

  /** The one-time CLUSTER statements PostgreSQL offers (no maintained
   * clustered indexes there; re-running CLUSTER refreshes the order). */
  private postgresClusterSection(clustered: rmT.ITable[]): ExprNode<m2tmm.ISection> {
    return (
      <Sec name="physical_clustering">
        <SecParent $refByName="physical"></SecParent>
        <P>{`-- one-time physical clustering (PostgreSQL: re-run CLUSTER to refresh)`}</P>
        {clustered.map((tab) => (
          <P>{`CLUSTER ${this.quoteIdentifier(tab.name)} USING ${this.quoteIdentifier(String((tab.primaryKey as rmT.IPrimaryKey).name))};`}</P>
        ))}
        <P>{" "}</P>
      </Sec>
    )
  }

  /** The triggers document: connect rules always land here (no dialect
   * expresses them declaratively); under TriggerEmulation the
   * disconnect rules join them, and history capture stubs land here
   * unconditionally for every table carrying historyOf. The bodies are
   * named stubs: the rule, its event, and its meaning are the
   * generated contract. */
  @E2E()
  triggersDocument(s: rmT.IRelSchema, connectFks: rmT.IForeignKey[], emulatedFks: rmT.IForeignKey[], historyTables: rmT.ITable[]): ExprNode<m2tmm.IDocument> {
    return (
      <Doc name={`${s.name}-triggers.sql`}>
        <Sec name="triggers_header">
          <P>{`-- Referential-rule triggers generated by Synthesis from ${s.name}`}</P>
          <P>{" "}</P>
        </Sec>
        {connectFks.map((fk) => this.connectTrigger(fk))}
        {emulatedFks.map((fk) => this.disconnectTrigger(fk))}
        {historyTables.map((tab) => this.captureTrigger(tab))}
      </Doc>
    )
  }

  /** The row-history capture stub, unconditional like the connect
   * rules: no dialect maintains a history table declaratively, so
   * every update or delete on the base table writes the previous row
   * state (with its discriminator value) through the named
   * procedure. */
  private captureTrigger(tab: rmT.ITable): ExprNode<m2tmm.ISection> {
    const base = (tab.historyOf as rmT.ITable).name
    return (
      <Sec name={`trg_${tab.name}_capture`}>
        <P>{`-- row history capture for ${base}: every update or delete writes the previous row state to ${tab.name}`}</P>
        <P>{`CREATE TRIGGER ${this.quoteIdentifier(`trg_${tab.name}_capture`)}`}</P>
        <P>{`  AFTER UPDATE OR DELETE ON ${this.quoteIdentifier(String(base))}`}</P>
        <P>{`  FOR EACH ROW EXECUTE PROCEDURE ${this.quoteIdentifier(`synth_${tab.name}_capture`)}();`}</P>
        <P>{" "}</P>
      </Sec>
    )
  }

  private connectTrigger(fk: rmT.IForeignKey): ExprNode<m2tmm.ISection> {
    const owner = (fk.ownerTable as rmT.ITable).name
    return (
      <Sec name={`trg_${fk.name}_connect`}>
        <P>{`-- connect rule ${String(fk.onConnect)} for ${fk.name}: connecting a ${owner} row governs the referenced row`}</P>
        <P>{`CREATE TRIGGER ${this.quoteIdentifier(`trg_${fk.name}_connect`)}`}</P>
        <P>{`  BEFORE INSERT OR UPDATE ON ${this.quoteIdentifier(String(owner))}`}</P>
        <P>{`  FOR EACH ROW EXECUTE PROCEDURE ${this.quoteIdentifier(`synth_${fk.name}_connect`)}();`}</P>
        <P>{" "}</P>
      </Sec>
    )
  }

  private disconnectTrigger(fk: rmT.IForeignKey): ExprNode<m2tmm.ISection> {
    const referenced = (fk.referencedTable as rmT.ITable).name
    const rule = String(fk.onDelete ?? fk.onUpdate)
    return (
      <Sec name={`trg_${fk.name}_disconnect`}>
        <P>{`-- disconnect rule ${rule} for ${fk.name}: deleting or re-keying a ${referenced} row governs the referencing rows`}</P>
        <P>{`CREATE TRIGGER ${this.quoteIdentifier(`trg_${fk.name}_disconnect`)}`}</P>
        <P>{`  AFTER DELETE OR UPDATE ON ${this.quoteIdentifier(String(referenced))}`}</P>
        <P>{`  FOR EACH ROW EXECUTE PROCEDURE ${this.quoteIdentifier(`synth_${fk.name}_disconnect`)}();`}</P>
        <P>{" "}</P>
      </Sec>
    )
  }

  @E2E()
  tableToCreate(tab: rmT.ITable): ExprNode<m2tmm.ISection> {
    const cols = (tab.columns || []) as rmT.IColumn[]
    if (cols.length === 0) {
      throw new Error(`Table '${tab.name}' has no columns; nothing to create.`)
    }
    // key-ness is membership in the table's PrimaryKey, in ITS order
    const keyCols = ((tab.primaryKey as rmT.IPrimaryKey | undefined)?.columns ?? []) as rmT.IColumn[]
    const keySet = new Set<rmT.IColumn>(keyCols)
    const lines: string[] = cols.map((c) => `  ${this.columnLine(c, keySet.has(c))}`)
    if (keyCols.length > 0) {
      lines.push(`  PRIMARY KEY (${keyCols.map((c) => this.quoteIdentifier(c.name)).join(", ")})`)
    }
    return (
      <Sec name={`table_${tab.name}`}>
        <SecParent $refByName="tables"></SecParent>
        <P>{`CREATE TABLE ${this.quoteIdentifier(tab.name)} (`}</P>
        {lines.map((line, i) => (
          <P>{`${line}${i < lines.length - 1 ? "," : ""}`}</P>
        ))}
        <P>{`)${this.tableOrganizationSuffix(tab)};`}</P>
        <P>{" "}</P>
      </Sec>
    )
  }

  @E2E()
  foreignKeyToAlter(fk: rmT.IForeignKey): ExprNode<m2tmm.ISection> {
    const owner = fk.ownerTable as rmT.ITable | undefined
    const referenced = fk.referencedTable as rmT.ITable | undefined
    const pairs = (fk.fkColumns ?? []) as rmT.IForeignKeyColumn[]
    if (!owner || !referenced || pairs.length === 0) {
      throw new Error(`Foreign key '${fk.name}' is incomplete: it needs an owner, a referenced table, and column pairs.`)
    }
    const fkCols = pairs.map((p) => {
      const col = p.fkColumn as rmT.IColumn | undefined
      if (!col) throw new Error(`Foreign key '${fk.name}' has a pair without its fk column.`)
      return this.quoteIdentifier(col.name)
    })
    const refCols = pairs.map((p) => {
      const col = p.refColumn as rmT.IColumn | undefined
      if (!col) throw new Error(`Foreign key '${fk.name}' has a pair without its referenced column.`)
      return this.quoteIdentifier(col.name)
    })
    return (
      <Sec name={`constraint_${owner.name}_${fk.name}`}>
        <SecParent $refByName="constraints"></SecParent>
        <P>{`ALTER TABLE ${this.quoteIdentifier(owner.name)} ADD CONSTRAINT ${this.quoteIdentifier(fk.name)}`}</P>
        <P>{`  FOREIGN KEY (${fkCols.join(", ")}) REFERENCES ${this.quoteIdentifier(referenced.name)} (${refCols.join(", ")})${this.fkActionClauses(fk)};`}</P>
        <P>{" "}</P>
      </Sec>
    )
  }

  private actionSql(action: string): string {
    switch (action) {
      case "Cascade": return "CASCADE"
      case "SetNull": return "SET NULL"
      case "SetDefault": return "SET DEFAULT"
      default: return "RESTRICT"
    }
  }

  @E2E()
  indexToCreate(ix: rmT.IIndex): ExprNode<m2tmm.ISection> {
    const owner = ix.ownerTable as rmT.ITable | undefined
    const cols = (ix.columns ?? []) as rmT.IColumn[]
    if (!owner || cols.length === 0) {
      throw new Error(`Index '${ix.name}' is incomplete: it needs an owner table and at least one column.`)
    }
    const unique = ix.isUnique ? "UNIQUE " : ""
    return (
      <Sec name={`index_${owner.name}_${ix.name}`}>
        <SecParent $refByName="indexes"></SecParent>
        <P>{`CREATE ${unique}INDEX ${this.quoteIdentifier(ix.name)} ON ${this.quoteIdentifier(owner.name)} (${cols.map((c) => this.quoteIdentifier(c.name)).join(", ")});`}</P>
        <P>{" "}</P>
      </Sec>
    )
  }

  private columnLine(c: rmT.IColumn, isKeyColumn: boolean): string {
    const parts: string[] = [this.quoteIdentifier(c.name), this.columnTypeText(c)]
    if (c.isAutoincrement) parts.push("AUTOINCREMENT")
    const domainFacts = this.columnDomainClauses(c)
    if (domainFacts.default !== undefined) parts.push(domainFacts.default)
    if (c.isNullable === false && !isKeyColumn) parts.push("NOT NULL")
    if (domainFacts.check !== undefined) parts.push(domainFacts.check)
    return parts.join(" ")
  }

  // ######### START DomainHandling variations #############

  /** The domain statements section: nothing inline, CREATE DOMAIN when
   * domains are emitted. */
  @VarPoint("DomainHandling")
  domainsHandling(domains: rmT.IDomain[]): ExprNode<m2tmm.ISection>[] {
    throw new Error("Not implemented VarOptions for VarPoint DomainHandling")
  }

  @Default()
  @VarOption("domainsHandling", Option("InlineTypes"))
  inlineNoDomainStatements(domains: rmT.IDomain[]): ExprNode<m2tmm.ISection>[] {
    return []
  }

  @VarOption("domainsHandling", Option("EmitDomains"))
  emitDomainStatements(domains: rmT.IDomain[]): ExprNode<m2tmm.ISection>[] {
    return domains.map((d) => (
      <Sec name={`domain_${d.name}`}>
        <SecParent $refByName="domains"></SecParent>
        <P>{`CREATE DOMAIN ${this.quoteIdentifier(String(d.name))} AS ${d.type}${d.defaultValue !== undefined && d.defaultValue !== null ? ` DEFAULT ${d.defaultValue}` : ""}${d.check !== undefined && d.check !== null ? ` CHECK (${d.check})` : ""};`}</P>
        <P>{" "}</P>
      </Sec>
    ))
  }

  /** A domain-linked column's type text: the base type inline, or the
   * domain's name when domains are emitted. */
  @VarPoint("DomainHandling")
  columnTypeText(c: rmT.IColumn): string {
    throw new Error("Not implemented VarOptions for VarPoint DomainHandling")
  }

  @Default()
  @VarOption("columnTypeText", Option("InlineTypes"))
  inlineColumnType(c: rmT.IColumn): string {
    return c.type
  }

  @VarOption("columnTypeText", Option("EmitDomains"))
  domainColumnType(c: rmT.IColumn): string {
    const d = c.domain as rmT.IDomain | undefined
    return d !== undefined && d !== null ? this.quoteIdentifier(String(d.name)) : c.type
  }

  /** A domain-linked column's inline clauses: DEFAULT and CHECK carried
   * onto the column when types are inlined (VALUE becomes the column's
   * identifier), nothing when the domain statement carries them. */
  @VarPoint("DomainHandling")
  columnDomainClauses(c: rmT.IColumn): { default?: string; check?: string } {
    throw new Error("Not implemented VarOptions for VarPoint DomainHandling")
  }

  @Default()
  @VarOption("columnDomainClauses", Option("InlineTypes"))
  inlineDomainClauses(c: rmT.IColumn): { default?: string; check?: string } {
    const d = c.domain as rmT.IDomain | undefined
    if (d === undefined || d === null) return {}
    return {
      ...(d.defaultValue !== undefined && d.defaultValue !== null ? { default: `DEFAULT ${d.defaultValue}` } : {}),
      ...(d.check !== undefined && d.check !== null
        ? { check: `CHECK (${String(d.check).split("VALUE").join(this.quoteIdentifier(c.name))})` }
        : {}),
    }
  }

  @VarOption("columnDomainClauses", Option("EmitDomains"))
  noInlineDomainClauses(c: rmT.IColumn): { default?: string; check?: string } {
    return {}
  }

  // ######### START ReferentialActions variations #############

  /** The action clauses appended to a FOREIGN KEY line. */
  @VarPoint("ReferentialActions")
  fkActionClauses(fk: rmT.IForeignKey): string {
    throw new Error("Not implemented VarOptions for VarPoint ReferentialActions")
  }

  @Default()
  @VarOption("fkActionClauses", Option("NativeDdl"))
  nativeActionClauses(fk: rmT.IForeignKey): string {
    const onDelete = fk.onDelete !== undefined && fk.onDelete !== null ? ` ON DELETE ${this.actionSql(String(fk.onDelete))}` : ""
    const onUpdate = fk.onUpdate !== undefined && fk.onUpdate !== null ? ` ON UPDATE ${this.actionSql(String(fk.onUpdate))}` : ""
    return `${onDelete}${onUpdate}`
  }

  @VarOption("fkActionClauses", Option("TriggerEmulation"))
  noActionClauses(fk: rmT.IForeignKey): string {
    return ""
  }

  /** Which foreign keys need disconnect triggers: none natively, the
   * action-carrying ones under emulation. */
  @VarPoint("ReferentialActions")
  disconnectTriggerFks(fks: rmT.IForeignKey[]): rmT.IForeignKey[] {
    throw new Error("Not implemented VarOptions for VarPoint ReferentialActions")
  }

  @Default()
  @VarOption("disconnectTriggerFks", Option("NativeDdl"))
  noDisconnectTriggers(fks: rmT.IForeignKey[]): rmT.IForeignKey[] {
    return []
  }

  @VarOption("disconnectTriggerFks", Option("TriggerEmulation"))
  emulatedDisconnectTriggers(fks: rmT.IForeignKey[]): rmT.IForeignKey[] {
    return fks.filter((fk) => (fk.onDelete !== undefined && fk.onDelete !== null) || (fk.onUpdate !== undefined && fk.onUpdate !== null))
  }

  // ######### START SqlDialect and Clustering variations #############

  /** The dialect flavoring the physical emissions. */
  @VarPoint("SqlDialect")
  dialect(): "standard" | "postgres" | "oracle" {
    throw new Error("Not implemented VarOptions for VarPoint SqlDialect")
  }

  @Default()
  @VarOption("dialect", Option("StandardSql"))
  standardDialect(): "standard" { return "standard" }

  @VarOption("dialect", Option("PostgreSql"))
  postgresDialect(): "postgres" { return "postgres" }

  @VarOption("dialect", Option("Oracle"))
  oracleDialect(): "oracle" { return "oracle" }

  /** The per-table clustering decision. */
  @VarPoint("Clustering")
  clusteringOf(tab: rmT.ITable): "none" | "pk" {
    throw new Error("Not implemented VarOptions for VarPoint Clustering")
  }

  @Default()
  @VarOption("clusteringOf", Option("None"))
  noClustering(tab: rmT.ITable): "none" { return "none" }

  @VarOption("clusteringOf", Option("ClusterPrimaryKey"))
  clusterByPrimaryKey(tab: rmT.ITable): "pk" { return "pk" }

  /** Oracle keeps a clustered table clustered: the same logical choice
   * becomes an index-organized table at creation. */
  private tableOrganizationSuffix(tab: rmT.ITable): string {
    return this.clusteringOf(tab) === "pk" && this.dialect() === "oracle" ? " ORGANIZATION INDEX" : ""
  }

  // ######### START IdentifierQuoting variations #############

  @VarPoint("IdentifierQuoting")
  quoteIdentifier(name: string): string {
    throw new Error("Not implemented VarOptions for VarPoint IdentifierQuoting")
  }

  // @Default matches the decision model's `isDefault` on Unquoted: with no
  // configuration model at all (store-only construction), the VarPoint
  // dispatcher falls back to this option instead of throwing.
  @Default()
  @VarOption("quoteIdentifier", Option("Unquoted"))
  unquotedIdentifier(name: string): string {
    return name
  }

  @VarOption("quoteIdentifier", Option("DoubleQuoted"))
  doubleQuotedIdentifier(name: string): string {
    return `"${name}"`
  }

  // ######### END IdentifierQuoting variations #############
}
