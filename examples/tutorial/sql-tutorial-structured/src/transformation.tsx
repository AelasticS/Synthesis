/** @jsx createExprNode */

/**
 * Model-to-text tutorial, Part 2: the same DDL, in two files instead of
 * one. Every <Doc> in an M2T model becomes one file, so a second file is
 * a second document and nothing more.
 *
 * The split is not cosmetic. Foreign keys can be circular (two tables
 * referencing each other, or a table referencing itself), so no ordering
 * of CREATE TABLE statements can satisfy every inline REFERENCES clause.
 * Production DDL creates every table first and adds the foreign keys
 * afterwards with ALTER TABLE. The document structure follows the
 * deployment order.
 *
 * The template reads the model once, builds each statement as a named
 * value, and then composes the two documents from those values. The
 * final expression is the file structure, which is the point: what the
 * transformation produces can be read without following a rule anywhere
 * else.
 */
import { createExprNode } from '@aelastics/synthesis/jsx'
import { abstractM2M } from '@aelastics/synthesis/m2m'
import { M2T, Doc, Sec, P } from '@aelastics/synthesis/m2t'
import type { ModelStore } from '@aelastics/synthesis/store'
import * as m2tmm from '@aelastics/synthesis/m2t'
import * as rmT from 'rel-tutorial-metamodel/model'

/** One foreign key: the column that points, and the column it points at. */
type ForeignKey = {
  table: rmT.ITable
  column: rmT.IColumn
  targetTable: rmT.ITable
  targetColumn: rmT.IColumn
}

export class RelToSqlStructuredTransformation extends abstractM2M<rmT.IRelSchema, m2tmm.M2T_Model> {
  constructor(store: ModelStore) {
    super(store)
  }

  main(s: rmT.IRelSchema) {
    // Read the model once, up front: the tables to create, and every
    // foreign key that has to be added after they all exist.
    const tables = this.tablesOf(s)
    const foreignKeys = this.foreignKeysOf(s)

    // One section per statement. Each is an ordinary value, so the
    // documents below can be read as the files they produce.
    const createStatements = tables.map((tab) => {
      const cols = tab.columns ?? []
      return (
        <Sec name={`table_${tab.name}`}>
          <P>{`CREATE TABLE ${tab.name} (`}</P>
          {cols.map((c, i) => (
            <P>{`  ${this.columnLine(c)}${i < cols.length - 1 ? ',' : ''}`}</P>
          ))}
          <P>{');'}</P>
          <P>{' '}</P>
        </Sec>
      )
    })

    const alterStatements = foreignKeys.map((fk) => {
      const constraint = `fk_${fk.table.name}_${fk.column.name}`
      return (
        <Sec name={`constraint_${fk.table.name}_${fk.column.name}`}>
          <P>{`ALTER TABLE ${fk.table.name} ADD CONSTRAINT ${constraint}`}</P>
          <P>{`  FOREIGN KEY (${fk.column.name}) REFERENCES ${fk.targetTable.name}(${fk.targetColumn.name});`}</P>
          <P>{' '}</P>
        </Sec>
      )
    })

    // Two documents, so two files. Each states its whole content.
    const tablesFile = (
      <Doc name={`${s.name}.sql`}>
        <P>{`-- Tables of ${s.name}, generated by Synthesis`}</P>
        <P>{' '}</P>
        {createStatements}
      </Doc>
    )

    const constraintsFile = (
      <Doc name={`${s.name}-constraints.sql`}>
        <P>{`-- Foreign key constraints of ${s.name}, generated by Synthesis`}</P>
        <P>{`-- Apply after ${s.name}.sql: references may be circular, so`}</P>
        <P>{'-- every table has to exist before any of them is constrained.'}</P>
        <P>{' '}</P>
        {alterStatements}
      </Doc>
    )

    return (
      <M2T name={`${s.name}_sql`}>
        {tablesFile}
        {constraintsFile}
      </M2T>
    )
  }

  private columnLine(c: rmT.IColumn): string {
    const parts: string[] = [c.name, c.type]
    if (c.isKey) {
      parts.push('PRIMARY KEY')
    }
    if (c.isAutoincrement) {
      parts.push('AUTOINCREMENT')
    }
    if (!c.isNullable) {
      parts.push('NOT NULL')
    }
    return parts.join(' ')
  }

  private tablesOf(s: rmT.IRelSchema): rmT.ITable[] {
    return s.elements.filter((el) => this.context.store.isTypeOf(el, rmT.Table)) as rmT.ITable[]
  }

  // Every referencing column of the schema, paired with the table and
  // column it points at. A column is a foreign key exactly when it has a
  // reference, so this walk is the complete list.
  private foreignKeysOf(s: rmT.IRelSchema): ForeignKey[] {
    const tables = this.tablesOf(s)
    const keys: ForeignKey[] = []
    for (const table of tables) {
      for (const column of table.columns ?? []) {
        if (column.references) {
          keys.push({
            table,
            column,
            targetTable: this.tableOwning(s, column.references),
            targetColumn: column.references
          })
        }
      }
    }
    return keys
  }

  // A column does not know its table, so the table an ALTER TABLE
  // statement has to name is the one whose columns contain the
  // referenced column.
  private tableOwning(s: rmT.IRelSchema, col: rmT.IColumn): rmT.ITable {
    const owner = this.tablesOf(s).find((tab) => (tab.columns ?? []).some((c) => c.name === col.name))
    if (!owner) {
      throw new Error(`Column '${col.name}' is referenced but belongs to no table of schema '${s.name}'`)
    }
    return owner
  }
}
