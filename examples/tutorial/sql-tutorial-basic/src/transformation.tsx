/** @jsx createExprNode */

/**
 * Model-to-text tutorial, Part 1: a relational schema becomes one SQL
 * DDL file, with fixed logic and no decorators.
 *
 * Generating text in Synthesis is a transformation like any other. The
 * only thing that changes is the target metamodel: instead of a domain
 * language, the template builds a document tree out of the engine's
 * text-document metamodel (M2T, Doc, Sec, P). The CLI's generate step
 * then serializes every Doc in the result to one file under --out-dir,
 * so the shape of the document tree is the shape of the output.
 *
 * The whole schema maps to a single document here. Part 2 splits it into
 * two, and Part 3 turns the split itself into a decision.
 */
import { createExprNode } from '@aelastics/synthesis/jsx'
import type { ExprNode } from '@aelastics/synthesis/jsx'
import { abstractM2M } from '@aelastics/synthesis/m2m'
import { M2T, Doc, Sec, P } from '@aelastics/synthesis/m2t'
import type { ModelStore } from '@aelastics/synthesis/store'
import * as m2tmm from '@aelastics/synthesis/m2t'
import * as rmT from 'rel-tutorial-metamodel/model'

export class RelToSqlBasicTransformation extends abstractM2M<rmT.IRelSchema, m2tmm.M2T_Model> {
  constructor(store: ModelStore) {
    super(store)
  }

  // One <Doc> means one file. Its name is the file name the CLI writes,
  // so the schema name carries straight through to Library_rel.sql.
  main(s: rmT.IRelSchema) {
    return (
      <M2T name={`${s.name}_sql`}>
        <Doc name={`${s.name}.sql`}>
          <Sec name="header">
            <P>{`-- SQL DDL generated by Synthesis from ${s.name}`}</P>
            <P>{' '}</P>
          </Sec>
          {this.tablesOf(s).map((tab) => this.tableToCreate(s, tab))}
        </Doc>
      </M2T>
    )
  }

  // A section groups the paragraphs of one statement. Sections nest
  // directly in the document here, so the file follows the order the
  // template emits them in; Part 2 replaces that order with named
  // placement.
  tableToCreate(s: rmT.IRelSchema, tab: rmT.ITable): ExprNode<m2tmm.ISection> {
    const cols = tab.columns ?? []
    return (
      <Sec name={`table_${tab.name}`}>
        <P>{`CREATE TABLE ${tab.name} (`}</P>
        {cols.map((c, i) => (
          <P>{`  ${this.columnLine(s, c)}${i < cols.length - 1 ? ',' : ''}`}</P>
        ))}
        <P>{');'}</P>
        <P>{' '}</P>
      </Sec>
    )
  }

  // Every clause of a column definition comes from one property of the
  // column: there is no hidden state and no lookup table.
  private columnLine(s: rmT.IRelSchema, c: rmT.IColumn): string {
    const parts: string[] = [c.name, c.type]
    if (c.isKey) {
      parts.push('PRIMARY KEY')
    }
    if (c.isAutoincrement) {
      parts.push('AUTOINCREMENT')
    }
    if (!c.isNullable) {
      parts.push('NOT NULL')
    }
    // A column is a foreign key exactly when it references another
    // column; the metamodel keeps no separate flag that could disagree.
    if (c.references) {
      parts.push(`REFERENCES ${this.tableOwning(s, c.references).name}(${c.references.name})`)
    }
    return parts.join(' ')
  }

  // Tables are the schema's model elements, so they are found by type
  // rather than by a dedicated property.
  private tablesOf(s: rmT.IRelSchema): rmT.ITable[] {
    return s.elements.filter((el) => this.context.store.isTypeOf(el, rmT.Table)) as rmT.ITable[]
  }

  // A column does not know its table: the reference goes one way, from
  // the foreign key to the primary key column it points at. The table a
  // REFERENCES clause has to name is therefore the one table in the
  // schema whose columns contain that column.
  private tableOwning(s: rmT.IRelSchema, col: rmT.IColumn): rmT.ITable {
    const owner = this.tablesOf(s).find((tab) => (tab.columns ?? []).some((c) => c.name === col.name))
    if (!owner) {
      throw new Error(`Column '${col.name}' is referenced but belongs to no table of schema '${s.name}'`)
    }
    return owner
  }
}
