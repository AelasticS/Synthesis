import { readFile } from 'node:fs/promises'

import { Flags } from '@oclif/core'

import { BaseCommand } from '../../base/base-command.js'
import { getModelsPath } from '../../config/index.js'
import { parseSynthHeader } from '../../models/header.js'
import { listModels } from '../../support/refs.js'

interface ConfigRow {
  ref: string
  tx: string | null
  sourceModel: string | null
  description: string
}

export default class ConfigLs extends BaseCommand {
  static override description =
    'List configuration models in the workspace (models whose header declares kind configuration-model), optionally filtered by transformation.'

  static override examples = [
    '<%= config.bin %> <%= command.id %>',
    '<%= config.bin %> <%= command.id %> --for eer-to-relational'
  ]

  static override flags = {
    for: Flags.string({
      description: 'Only configurations generated by this transformation.'
    })
  }

  public async execute(): Promise<void> {
    const { flags } = await this.parse(ConfigLs)
    const json = Boolean(flags.json)

    const modelsDir = getModelsPath(this.workspaceConfig)
    const rows: ConfigRow[] = []
    for (const entry of await listModels(modelsDir)) {
      // Static fast path only: no transpile, no execution. Unreadable or
      // headerless files simply are not configuration models.
      let text: string
      try {
        text = await readFile(entry.path, 'utf-8')
      } catch {
        continue
      }
      const { header } = parseSynthHeader(text)
      if (header === null || header.kind !== 'configuration-model') {
        continue
      }
      const tx = header.generatedBy?.tx ?? null
      if (flags.for !== undefined && tx !== flags.for) {
        continue
      }
      rows.push({
        ref: entry.ref,
        tx,
        sourceModel: header.references.sourceModel ?? null,
        description: header.description
      })
    }

    if (json) {
      this.log(JSON.stringify(rows))
      return
    }

    if (rows.length === 0) {
      this.log(
        flags.for !== undefined
          ? `No configuration models found for transformation: ${flags.for}`
          : 'No configuration models found.'
      )
      return
    }

    const width = Math.max(...rows.map((row) => row.ref.length))
    for (const row of rows) {
      this.log(`${row.ref.padEnd(width)}  ${row.tx ?? '(authored)'}  for ${row.sourceModel ?? '(unknown)'}`)
    }
  }
}
