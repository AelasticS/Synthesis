/**
 * Model-to-text transformation that turns a relational schema into a
 * single-document M2T model containing SQL DDL (CREATE TABLE statements).
 *
 * The relational schema's columns are already named according to the
 * decision-driven naming convention chosen upstream (snake_case vs
 * camelCase), so this template emits identifiers verbatim. Empty tables
 * (no columns) are skipped.
 *
 * The transformation is decision-aware: the IdentifierQuoting issue of
 * its decision model (02-decision-model.tsx) selects how table/column
 * identifiers are emitted — verbatim (Unquoted, the default) or wrapped
 * in double quotes (DoubleQuoted).
 */
let Rel2DdlTransformation = class Rel2DdlTransformation extends variability_1.DecisionAwareM2M {
    constructor(store, extra, configModel) {
        super(store, extra ?? {}, configModel);
    }
    topRule(s) {
        return ((0, jsx_1.createExprNode)(m2t_1.M2T, { name: `${s.name}_ddl` },
            (0, jsx_1.createExprNode)(m2t_1.Doc, { name: `${s.name}.sql` },
                (0, jsx_1.createExprNode)(m2t_1.Sec, { name: "header" },
                    (0, jsx_1.createExprNode)(m2t_1.P, null, `-- SQL DDL generated by Synthesis from ${s.name}`),
                    (0, jsx_1.createExprNode)(m2t_1.P, null, " ")),
                (0, jsx_1.createExprNode)(m2t_1.Sec, { name: "tables" })),
            s.elements
                .filter((el) => this.context.store.isTypeOf(el, rmT.Table))
                .map((tab) => this.tableToCreate(tab))));
    }
    tableToCreate(tab) {
        const cols = (tab.columns || []);
        return ((0, jsx_1.createExprNode)(m2t_1.Sec, { name: `table_${tab.name}` },
            (0, jsx_1.createExprNode)(m2t_1.SecParent, { "$refByName": "tables" }),
            (0, jsx_1.createExprNode)(m2t_1.P, null, `CREATE TABLE ${this.quoteIdentifier(tab.name)} (`),
            cols.map((c, i) => ((0, jsx_1.createExprNode)(m2t_1.P, null, `  ${this.columnLine(c)}${i < cols.length - 1 ? "," : ""}`))),
            (0, jsx_1.createExprNode)(m2t_1.P, null, `);`),
            (0, jsx_1.createExprNode)(m2t_1.P, null, " ")));
    }
    columnLine(c) {
        const parts = [this.quoteIdentifier(c.name), c.type];
        if (c.isKey)
            parts.push("PRIMARY KEY");
        if (c.isAutoincrement)
            parts.push("AUTOINCREMENT");
        if (c.isForeignKey && c.references)
            parts.push(`REFERENCES ${this.quoteIdentifier(c.references)}`);
        if (c.isNullable === false && !c.isKey)
            parts.push("NOT NULL");
        return parts.join(" ");
    }
    // ######### START IdentifierQuoting variations #############
    quoteIdentifier(name) {
        throw new Error("Not implemented VarOptions for VarPoint IdentifierQuoting");
    }
    // @Default matches the decision model's `isDefault` on Unquoted: with no
    // configuration model at all (store-only construction), the VarPoint
    // dispatcher falls back to this option instead of throwing.
    unquotedIdentifier(name) {
        return name;
    }
    doubleQuotedIdentifier(name) {
        return `"${name}"`;
    }
};
